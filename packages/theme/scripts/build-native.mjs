// Writes src/tokens.native.ts: the colours of src/tokens.ts as hex, because React Native cannot draw oklch().
//   node packages/theme/scripts/build-native.mjs           write the file
//   node packages/theme/scripts/build-native.mjs --check   fail when the file is missing or out of date
// scripts/check-web-rules.mjs runs the check before every web typecheck/build, so the two cannot drift.
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { oklchToHex } from './oklch.mjs';

const THEME = path.resolve(import.meta.dirname, '..');
const SOURCE = path.join(THEME, 'src/tokens.ts');
const TARGET = path.join(THEME, 'src/tokens.native.ts');

/** The text tokens.native.ts must have, made from tokens.ts. */
export function renderNative(source = readFileSync(SOURCE, 'utf8')) {
  const block = (start) => {
    const from = source.indexOf(start);
    if (from < 0) throw new Error(`tokens.ts: "${start}" not found`);
    return source.slice(from, source.indexOf('}', from));
  };
  const entries = (start) => [...block(start).matchAll(/^\s*(\w+):\s*'(oklch\([^)]*\))'/gm)].map(([, name, value]) => [name, oklchToHex(value)]);
  const radius = /export const radius = (\d+)/.exec(source)?.[1];
  if (!radius) throw new Error('tokens.ts: radius not found');
  const obj = (pairs) => pairs.map(([k, v]) => `  ${k}: '${v}',`).join('\n');
  const light = entries('export const light = {');
  const dark = entries('export const dark');
  if (!light.length || light.length !== dark.length) throw new Error('tokens.ts: light and dark must list the same colours');
  return `// GENERATED by packages/theme/scripts/build-native.mjs from src/tokens.ts — do not edit by hand.
// The same design tokens as hex colours for React Native (apps/mobile), which cannot draw oklch().
// After changing tokens.css / tokens.ts run:  node packages/theme/scripts/build-native.mjs
export const radius = ${radius};

export const light = {
${obj(light)}
} as const;

export const dark: Record<keyof typeof light, string> = {
${obj(dark)}
};

export type ColorToken = keyof typeof light;
`;
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === path.resolve(import.meta.filename);
if (isMain) {
  const want = renderNative();
  if (process.argv.includes('--check')) {
    let have = '';
    try {
      have = readFileSync(TARGET, 'utf8').replace(/\r\n/g, '\n');
    } catch {}
    if (have !== want) {
      console.error('✖ packages/theme/src/tokens.native.ts is out of date. Run: node packages/theme/scripts/build-native.mjs');
      process.exit(1);
    }
    console.log('✔ tokens.native.ts matches tokens.ts');
  } else {
    writeFileSync(TARGET, want);
    console.log(`✔ Wrote ${path.relative(process.cwd(), TARGET)}`);
  }
}
